import { Database } from "bun:sqlite";
import { expect, test } from "bun:test";
import { sqliteComputedColumnDdl } from "../tools/computed-columns";
import { computedExpressionError } from "../tools/database-ir";
import { generateProject } from "../tools/generate-project";
import { parseQiyProject } from "../tools/qiy-project";

const source = `qiy v0; application computed-demo {
  database sqlite {}
  entity people {
    field id UUID @id;
    field first Text;
    field last Text;
    field fullName Text @computed("{first} {last}");
  }
}`;

const numericSource = `qiy v0; application computed-demo {
  database postgresql {}
  entity lines {
    field id UUID @id;
    field quantity Integer;
    field price Decimal(10,2) @nullable;
    field total Decimal(12,2) @nullable @computed("{quantity} * {price}");
    field half Integer @nullable @computed("({quantity} + 1) / 2");
  }
}`;

test("@computed renders a database generated column in every dialect", () => {
  const sqlite = generateProject(parseQiyProject(source).database, "computed-demo");
  expect(sqlite["apps/server/src/schema.ts"]).toContain('import { sql } from "drizzle-orm";');
  expect(sqlite["apps/server/src/schema.ts"]).toContain(`"fullName": text("fullName").notNull().generatedAlwaysAs(sql.raw(${JSON.stringify(`COALESCE("first", '') || ' ' || COALESCE("last", '')`)}), { mode: "virtual" })`);
  const repository = sqlite["apps/server/src/modules/people/people.repository.ts"]!;
  expect(repository).not.toContain("qiyComputeRecord");
  expect(repository).toContain('"fullName": people.fullName');
  const web = sqlite["apps/web/app/resources.ts"]!;
  expect(web).toContain('"autoGenerated": true');
  expect(web).not.toContain('"sortable": false');
  const mysql = generateProject(parseQiyProject(source.replace("database sqlite", "database mysql")).database, "computed-demo");
  expect(mysql["apps/server/src/schema.ts"]).toContain(JSON.stringify("CONCAT(COALESCE(`first`, ''), ' ', COALESCE(`last`, ''))"));
});

test("numeric @computed columns divide as decimals, null out division by zero and keep the declared scale", () => {
  const schema = (dialect: string) => generateProject(parseQiyProject(numericSource.replace("database postgresql", `database ${dialect}`)).database, "computed-demo")["apps/server/src/schema.ts"]!;
  expect(schema("postgresql")).toContain(JSON.stringify('CAST(CAST("quantity" AS numeric) * CAST("price" AS numeric) AS numeric(12, 2))'));
  expect(schema("postgresql")).toContain(JSON.stringify('CAST(TRUNC((CAST("quantity" AS numeric) + 1) / NULLIF(2, 0)) AS integer)'));
  expect(schema("postgresql")).not.toContain("mode: \"virtual\"");
  expect(schema("mysql")).toContain(JSON.stringify("CAST(TRUNCATE((`quantity` + 1) / NULLIF(2, 0), 0) AS SIGNED)"));
  expect(schema("sqlite")).toContain(JSON.stringify('ROUND(CAST("quantity" AS REAL) * CAST("price" AS REAL), 2)'));
});

test("SQLite evaluates generated columns with the documented semantics", () => {
  const project = parseQiyProject(`qiy v0; application computed-demo {
  database sqlite {}
  entity lines {
    field id UUID @id;
    field label Text @nullable;
    field quantity Integer @nullable;
    field divisor Integer @nullable;
    field ratio Decimal(10,2) @nullable @computed("{quantity} / {divisor}");
    field whole Integer @nullable @computed("-{quantity} / {divisor}");
    field caption Text @computed("[{label}]");
  }
}`);
  const entity = project.database.entities[0]!;
  const columns = entity.fields.map((field) => field.computed !== undefined ? sqliteComputedColumnDdl(field, entity) : `"${field.name}" ${field.type === "Integer" ? "integer" : "text"}`);
  const db = new Database(":memory:");
  db.exec(`create table lines (${columns.join(", ")})`);
  db.exec("insert into lines (id, label, quantity, divisor) values ('a', 'x', 7, 3), ('b', null, 7, 0), ('c', 'y', null, 2)");
  expect(db.query("select id, ratio, whole, caption from lines order by id").all()).toEqual([
    { id: "a", ratio: 2.33, whole: -2, caption: "[x]" },
    { id: "b", ratio: null, whole: null, caption: "[]" },
    { id: "c", ratio: null, whole: null, caption: "[y]" },
  ]);
});

test("numeric @computed expressions are validated", () => {
  expect(computedExpressionError("{a} * ({b} - 1.5)")).toBeUndefined();
  expect(computedExpressionError("-{a} + 2")).toBeUndefined();
  expect(computedExpressionError("{a} * ")).toBe("is not a valid arithmetic expression");
  expect(computedExpressionError("({a}")).toBe("is not a valid arithmetic expression");
  expect(computedExpressionError("{a}; process.exit()")).toContain("may only contain");
  expect(computedExpressionError("1 + 2")).toBe("must reference at least one field");
  const build = (text: string) => () => generateProject(parseQiyProject(text).database, "computed-demo");
  expect(build(numericSource.replace("field total Decimal(12,2) @nullable", "field total Decimal(12,2)"))).toThrow("numeric @computed fields must be @nullable");
  expect(build(numericSource.replace("{quantity} * {price}", "{quantity} ** {price}"))).toThrow("is not a valid arithmetic expression");
  expect(build(numericSource.replace("({quantity} + 1) / 2", "{total} / 2"))).toThrow("cannot reference another computed field total");
});

test("@computed only references other Text fields", () => {
  expect(() => generateProject(parseQiyProject(source.replace("{first} {last}", "{missing}")).database, "computed-demo")).toThrow("unknown field missing");
  expect(() => generateProject(parseQiyProject(source.replace("field fullName Text @computed(\"{first} {last}\")", "field fullName Text @computed(\"{fullName}\")")).database, "computed-demo")).toThrow("cannot reference itself");
  expect(() => generateProject(parseQiyProject(source.replace("field fullName Text", "field fullName DateTime")).database, "computed-demo")).toThrow("currently supports Text, Integer, Decimal and Money");
  expect(() => generateProject(parseQiyProject(source.replace("field fullName Text @computed(\"{first} {last}\")", "field fullName Integer @nullable @computed(\"{first} + 1\")")).database, "computed-demo")).toThrow("must be Integer, Decimal or Money");
});
