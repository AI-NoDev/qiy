import { expect, test } from "bun:test";
import { generateProject } from "../tools/generate-project";
import { parseQiyProject } from "../tools/qiy-project";

const source = `qiy v0; application computed-demo {
  database sqlite {}
  entity people {
    field id UUID @id;
    field first Text;
    field last Text;
    field fullName Text @computed("{first} {last}");
  }
}`;

test("@computed adds read-only derived values without a DB column", () => {
  const project = parseQiyProject(source);
  const files = generateProject(project.database, "computed-demo");
  expect(files["apps/server/src/schema.ts"]).not.toContain("fullName");
  const repository = files["apps/server/src/modules/people/people.repository.ts"]!;
  expect(repository).toContain('"fullName"');
  expect(repository).toContain("qiyComputeRecord");
  expect(repository).toContain("String(row.first ?? \"\")");
  const web = files["apps/web/app/resources.ts"]!;
  expect(web).toContain('"fullName"');
  expect(web).toContain('"autoGenerated": true');
});

test("@computed only references other Text fields", () => {
  expect(() => generateProject(parseQiyProject(source.replace("{first} {last}", "{missing}")).database, "computed-demo")).toThrow("unknown field missing");
  expect(() => generateProject(parseQiyProject(source.replace("field fullName Text @computed(\"{first} {last}\")", "field fullName Text @computed(\"{fullName}\")")).database, "computed-demo")).toThrow("cannot reference itself");
  expect(() => generateProject(parseQiyProject(source.replace("field fullName Text", "field fullName Integer")).database, "computed-demo")).toThrow("currently supports Text");
});
