import { describe, expect, test } from "bun:test";
import { generateProject } from "../tools/generate-project";
import { parseQiyProject, serializeQiyProject } from "../tools/qiy-project";

const source = (fields: string, dialect = "sqlite", flows = "") => `qiy v0; application locking {
  database ${dialect} {}
  entity notes {
    field id UUID @id;
    field title Text;
${fields}
  }
${flows}
}`;

const retitle = `  dataflow retitle {
    allow roles admin;
    idempotency required;
    input {
      field noteId UUID @required;
      field title Text @required;
    }
    context { note = entity notes by id input.noteId @required; }
    step change { update note { title = input.title; } }
    result { return note; }
  }`;

const build = (fields: string, dialect = "sqlite", flows = "") => {
  const project = parseQiyProject(source(fields, dialect, flows));
  return generateProject(project.database, project.name, { dataflows: project.dataflows });
};
const generate = (dialect: string, flows = "") => build("    field revision Integer @version;", dialect, flows);

describe("@version optimistic locking", () => {
  test("parses, round-trips and starts the column at 1", () => {
    const project = parseQiyProject(source("    field revision Integer @version;"));
    expect(project.database.entities[0]!.fields.find((field) => field.name === "revision")?.version).toBe(true);
    expect(parseQiyProject(serializeQiyProject(project))).toEqual(project);
    expect(generate("sqlite")["apps/server/src/schema.ts"]).toContain('"revision": integer("revision").notNull().default(1)');
    expect(generate("postgresql")["apps/server/src/schema.ts"]).toContain('"revision": integer("revision").notNull().default(1)');
  });

  test("rejects invalid declarations", () => {
    expect(() => build("    field revision Text @version;")).toThrow("@version");
    expect(() => build("    field revision Integer @version @nullable;")).toThrow("@version");
    expect(() => build("    field revision Integer @version @default(2);")).toThrow("@version");
    expect(() => build("    field revision Integer @version;\n    field other Integer @version;")).toThrow("only one @version field");
  });

  test("conditions every dialect's update on the counter and maps conflicts to 409", () => {
    for (const dialect of ["sqlite", "postgresql", "mysql"]) {
      const files = generate(dialect);
      const repository = files["apps/server/src/modules/notes/notes.repository.ts"]!;
      expect(repository).toContain('import { QiyVersionConflict } from "../../concurrency";');
      expect(repository).toContain("revision: sql`${notes.revision} + 1`");
      expect(repository).toContain('throw new QiyVersionConflict("notes", id)');
      if (dialect === "mysql") expect(repository).toContain("existing.revision !== expectedVersion");
      else expect(repository).toContain("eq(notes.revision, expectedVersion)");
      expect(files["apps/server/src/concurrency.ts"]).toContain('errorKey = "version.conflict"');
      const routes = files["apps/server/src/modules/notes/notes.routes.ts"]!;
      expect(routes).toContain("error instanceof QiyVersionConflict ? status(409");
    }
    const sqlite = generate("sqlite");
    expect(sqlite["apps/server/tests/sqlite-version.test.ts"]).toContain("rejects.toBeInstanceOf(QiyVersionConflict)");
    expect(generate("postgresql")["apps/server/tests/sqlite-version.test.ts"]).toBeUndefined();
  });

  test("keeps the counter out of create inputs and moves it in dataflows", () => {
    const files = generate("sqlite", retitle);
    const contract = files["apps/server/src/modules/notes/notes.contract.ts"]!;
    const createSchema = contract.slice(contract.indexOf("Create"), contract.indexOf("Update"));
    expect(createSchema).not.toContain("revision");
    const command = Object.entries(files).find(([path, text]) => path.startsWith("apps/server/src/") && text.includes("retitle") && text.includes(".revision + 1"));
    expect(command).toBeDefined();
    expect(() => generate("sqlite", retitle.replace("title = input.title;", 'revision = "9";'))).toThrow("@version counter and cannot be assigned");
  });

  test("ships the counter to the web form and leaves it out of lists", () => {
    const resources = generate("sqlite")["apps/web/app/resources.ts"]!;
    expect(resources).toContain('"versionField": "revision"');
    expect(resources).toMatch(/"name": "revision",[\s\S]*?"listVisible": false[\s\S]*?"autoGenerated": true/);
  });
});
