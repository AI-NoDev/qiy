import { expect, test } from "bun:test";
import { generateProject } from "../tools/generate-project";
import { parseQiyProject, serializeQiyProject } from "../tools/qiy-project";

const source = (claim = "tenantId") => `qiy v0; application tenant-demo {
  database sqlite {}
  auth {
    provider local;
    user users;
    subjectField email;
    roleField role;
    usernameField email;
    passwordField password;
  }
  enum userRole { value admin; value operator; value viewer; }
  entity users {
    field id UUID @id;
    field email Text @unique;
    field password Text @nullable;
    field role userRole;
    field tenantId UUID;
  }
  entity notes {
    field id UUID @id;
    field title Text;
    field tenantId UUID @tenant${claim === "tenantId" ? "" : `("${claim}")`};
  }
}`;

test("@tenant synthesizes a principal scope and hides the column", () => {
  const project = parseQiyProject(source());
  expect(project.scopes).toEqual([{ resource: "notes", field: "tenantId", claim: "tenantId", tenant: true }]);
  const serialized = serializeQiyProject(project);
  expect(serialized).toContain("@tenant(\"tenantId\")");
  expect(serialized).not.toContain("scope notes tenantId");
  const files = generateProject(project.database, "tenant-demo", project);
  expect(files["apps/server/src/modules/notes/notes.repository.ts"]).toContain("scopeCondition");
  expect(files["apps/web/app/resources.ts"]).toContain('"autoGenerated": true');
  expect(files["apps/server/src/modules/notes/notes.repository.ts"]).toContain("tenantId");
});

test("@tenant accepts a custom claim path", () => {
  const project = parseQiyProject(source("tenant.id"));
  expect(project.scopes?.[0]?.claim).toBe("tenant.id");
});

test("@tenant requires a non-null scalar column", () => {
  expect(() => generateProject(parseQiyProject(source().replace("field tenantId UUID @tenant", "field tenantId UUID @tenant @nullable")).database, "tenant-demo")).toThrow("@tenant requires a non-null field");
  expect(() => generateProject(parseQiyProject(source().replace("field tenantId UUID @tenant", "field tenantId DateTime @tenant")).database, "tenant-demo")).toThrow("@tenant requires UUID, Text or Integer");
});
