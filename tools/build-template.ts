/**
 * Builds `tools/admin-template.data.ts` from `templates/admin/`. Run this after
 * editing a template so the compiled `qiy` executable keeps shipping the
 * current data.
 *
 *   bun run tools/build-template.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import "./build-skill";

const root = resolve(import.meta.dir, "../templates/admin");
const output = join(import.meta.dir, "admin-template.data.ts");

const files: Record<string, string> = {};
function visit(directory: string): void {
  for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) visit(path);
    else if (entry.isFile()) files[relative(root, path).replaceAll("\\", "/")] = readFileSync(path, "utf8");
  }
}
visit(root);

const source = [
  "// Generated by tools/build-template.ts from templates/admin/. Do not edit by hand.",
  `export const ADMIN_TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};`,
  "",
].join("\n");

writeFileSync(output, source);
console.log(`Wrote ${Object.keys(files).length} template files to ${relative(resolve(import.meta.dir, ".."), output)}`);
