/** The server-side generated value specification for one entity, ready for JSON. */
export function generatedFieldSpecs(entity: EntityIR, database: DatabaseIR): Array<{ field: string; kind: "code" | "uuid"; template?: string }> {
  return generatedFieldsOf(entity, database.relations ?? []).map((generated) => ({
    field: generated.field.name,
    kind: generated.kind,
    ...(generated.template !== undefined ? { template: generated.template } : {}),
  }));
}

/** True when any entity needs the generated-values runtime module. */
export function usesGeneratedValues(database: DatabaseIR): boolean {
  return database.entities.some((entity) => generatedFieldsOf(entity, database.relations ?? []).length > 0);
}

function usesCodeTemplates(database: DatabaseIR): boolean {
  return database.entities.some((entity) => generatedFieldsOf(entity, database.relations ?? []).some((generated) => generated.kind === "code"));
}

